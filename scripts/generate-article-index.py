#!/usr/bin/env python3
"""Generate a lightweight article index for the client bundle.
This script reads all article files and extracts just the metadata,
so the client bundle doesn't include full article content.
"""
import re
import os
from pathlib import Path

SRC_DIR = Path("src/data")
OUTPUT_FILE = SRC_DIR / "article-index.ts"

# Files to scan for articles
ARTICLE_FILES = [
    "articles.ts",
    "articles_part2.ts",
    "articles_part3.ts",
    "articles_part4.ts",
    "articles_part5.ts",
    "articles_part6.ts",
    "articles_fill_june.ts",
    "articles_fill_july_p1.ts",
    "articles_fill_july_p2.ts",
    "articles_scheduled.ts",
    "articles_scheduled_august.ts",
    "articles_scheduled_august_part2.ts",
    "articles_scheduled_august_part3.ts",
    "articles_scheduled_august_part4.ts",
    "articles_scheduled_september.ts",
    "articles_travel_monetization.ts",
]

def extract_articles(content: str) -> list[dict]:
    """Extract article metadata from TypeScript file content."""
    articles = []
    
    # Match article objects with id, title, description, etc.
    # Pattern matches: id: "...", title: "...", description: "...", etc.
    pattern = r'\{[^}]*id:\s*"([^"]+)"[^}]*title:\s*"([^"]+)"[^}]*description:\s*"([^"]+)"[^}]*metaDescription:\s*"([^"]+)"[^}]*pubDate:\s*"([^"]+)"[^}]*author:\s*"([^"]+)"[^}]*category:\s*"([^"]+)"'
    
    for match in re.finditer(pattern, content, re.DOTALL):
        articles.append({
            "id": match.group(1),
            "title": match.group(2),
            "description": match.group(3),
            "metaDescription": match.group(4),
            "pubDate": match.group(5),
            "author": match.group(6),
            "category": match.group(7),
        })
    
    return articles

def main():
    all_articles = []
    
    for filename in ARTICLE_FILES:
        filepath = SRC_DIR / filename
        if not filepath.exists():
            continue
        
        content = filepath.read_text(encoding="utf-8")
        articles = extract_articles(content)
        all_articles.extend(articles)
        print(f"  {filename}: {len(articles)} articles")
    
    # Generate TypeScript file
    lines = [
        "// Auto-generated by scripts/generate-article-index.py",
        "// Do not edit manually — run the script instead.",
        "",
        "export interface ArticleIndex {",
        "  id: string;",
        "  postType: 'article' | 'page';",
        "  title: string;",
        "  description: string;",
        "  metaDescription: string;",
        "  pubDate: string;",
        "  author: string;",
        "  category: string;",
        "  tags: string[];",
        "  readingTime: number;",
        "  slug: string;",
        "  content?: string;",
        "  schema?: \"Article\" | \"WebPage\";",
        "}",
        "",
        f"export const ARTICLE_INDEX: ArticleIndex[] = [",
    ]
    
    for a in all_articles:
        lines.append(f"  {{")
        lines.append(f'    id: "{a["id"]}",')
        lines.append(f'    postType: "article",')
        lines.append(f'    title: "{a["title"]}",')
        lines.append(f'    description: "{a["description"]}",')
        lines.append(f'    metaDescription: "{a["metaDescription"]}",')
        lines.append(f'    pubDate: "{a["pubDate"]}",')
        lines.append(f'    author: "{a["author"]}",')
        lines.append(f'    category: "{a["category"]}",')
        lines.append(f'    tags: [],')
        lines.append(f'    readingTime: 5,')
        lines.append(f'    slug: "{a["id"]}",')
        lines.append(f"  }},")
    
    lines.append("];")
    lines.append("")
    lines.append(f"export const ARTICLE_COUNT = {len(all_articles)};")
    lines.append("")
    
    OUTPUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"\n✅ Generated {OUTPUT_FILE} with {len(all_articles)} articles")

if __name__ == "__main__":
    main()
